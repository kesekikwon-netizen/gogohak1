def build() -> list[str]:
    out, seen = [], set()

    def add(topic: str) -> None:
        q = f"[학술 심층] {topic} {RULE}"
        if q in seen:
            return
        seen.add(q)
        out.append(q)

    for t in WANGKYEONG + SOKYEONG:
        add(t)
    for s in SITES:
        add(f"경주 {s}의 발굴조사 연도·조사기관·보고서명, 주요 유구·유물, 편년, 학술적 쟁점을 정리하라.")
