    qs = build()
    p = Path(args.out)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(qs) + "\n", encoding="utf-8")
    print(f"{len(qs)}개 학술 심층 질문 -> {p}")
    return 0


